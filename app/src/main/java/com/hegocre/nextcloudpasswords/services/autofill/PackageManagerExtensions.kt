package com.hegocre.nextcloudpasswords.services.autofill

import android.content.pm.ApplicationInfo
import android.content.pm.PackageManager
import android.os.Build

internal fun PackageManager.getApplicationInfoCompat(
    packageName: String,
    flags: Long = 0L,
): ApplicationInfo {
    return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
        getApplicationInfo(packageName, PackageManager.ApplicationInfoFlags.of(flags))
    } else {
        @Suppress("DEPRECATION")
        getApplicationInfo(packageName, flags.toInt())
    }
}
